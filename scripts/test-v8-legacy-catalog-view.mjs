import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {createLegacyCatalogView,findLegacyEntity,preflightLegacyMappingCandidates} from './v8-legacy-catalog-view.mjs';

const bytes = readFileSync(new URL('../data.json',import.meta.url));
const actual = JSON.parse(bytes.toString('utf8'));
const source = {repository:'Super-pu921/ad-factory-learning',commit:'23b5af7e3b5843fb65638d5dbfb87e7a2250fc51',sha256:createHash('sha256').update(bytes).digest('hex')};
const before = structuredClone(actual);
const view = createLegacyCatalogView(actual,source);
assert.deepEqual(actual,before,'view creation must not mutate the source');
assert.deepEqual(view.catalog,actual,'all fields, values, arrays and their order must survive');
assert.deepEqual(view.audit.baseline.observed,{lessons:90,components:88,scenes:6,phases:13,componentCategories:10});
assert.deepEqual(view.audit.statistics,{lessonToComponent:203,componentToLesson:176,mutual:34,unilateral:311,deepDiveLessons:35,sourceRecords:31,resourceRecords:33});
assert.equal(view.catalog.anti.length,14);
assert.equal(view.catalog.templates.length,6);
assert.throws(() => { view.catalog.lessons[0].title = 'changed'; },TypeError);
const unknown = structuredClone(actual);
unknown.extra = JSON.parse('{"__proto__":{"polluted":true},"future":[1,null,"keep"]}');
const unknownView = createLegacyCatalogView(unknown,source);
assert.deepEqual(unknownView.catalog.extra,unknown.extra);
assert.ok(unknownView.uninterpretedFields.some(item=>item.path[0]==='extra'));
assert.equal({}.polluted,undefined);
assert.equal(Object.hasOwn(unknownView.catalog.extra,'__proto__'),true);
assert.equal(findLegacyEntity(view,'lessons',1).id,1);
assert.equal(findLegacyEntity(view,'lessons','1'),null,'numeric and string IDs must remain distinct');
assert.equal(findLegacyEntity(view,'scenes','customers').id,'customers');
assert.equal(findLegacyEntity(view,'templates','customers').id,'customers','same ID in a different collection remains independent');
assert.equal(findLegacyEntity(view,'resources',0),null,'array position is not a stable resource identity');
assert.equal(findLegacyEntity(view,'unknown','customers'),null);
const ambiguous = structuredClone(actual);ambiguous.components[1].id=ambiguous.components[0].id;
assert.equal(findLegacyEntity(createLegacyCatalogView(ambiguous,source),'components',ambiguous.components[0].id),null);
const cyclic={};cyclic.self=cyclic;
assert.throws(() => createLegacyCatalogView(cyclic),TypeError);
assert.throws(() => createLegacyCatalogView({fn:()=>{}}),TypeError);
assert.throws(() => createLegacyCatalogView({bad:Infinity}),TypeError);
assert.throws(() => createLegacyCatalogView({date:new Date()}),TypeError);
assert.equal(createLegacyCatalogView({}).audit.testCases[1].status,'BLOCKED');

// Explicitly synthetic target identities, never written into the formal catalog.
const target = id => ({namespace:'synthetic',entityType:'Unit',id,version:'fixture-v1'});
const src = id => ({namespace:'legacy',entityType:'lessons',id});
const group = (id,sources,targets,cardinality,role='IDENTITY') => ({groupId:id,role,cardinality,reviewStatus:'CANDIDATE',sourceSnapshot:{...source},evidence:['in-memory test only'],sources,targets});
const one=group('one',[src(1)],[target('a')],'1:1');
const declarations=[target('a'),target('b'),target('c')];
const run = (groups,targets=declarations) => preflightLegacyMappingCandidates(view,groups,targets);
const has = (report,code) => report.diagnostics.some(item=>item.code===code);
assert.equal(run([one]).status,'PASS');
assert.equal(run([group('split',[src(1)],[target('a'),target('b')],'1:N')]).status,'PASS','explicit 1:N is legitimate');
assert.equal(run([group('merge',[src(1),src(2)],[target('a')],'N:1')]).status,'PASS','explicit N:1 is legitimate');
assert.ok(has(run([group('cross',[src(1),src(2)],[target('a'),target('b')],'N:M')]),'INVALID_CARDINALITY'));
assert.ok(has(run([one,one]),'DUPLICATE_GROUP_ID'));
assert.ok(has(run([one,group('conflict',[src(1)],[target('b')],'1:1')]),'CONFLICTING_SOURCE_IDENTITY'));
assert.ok(has(run([one,group('conflict',[src(2)],[target('a')],'1:1')]),'CONFLICTING_TARGET_IDENTITY'));
assert.equal(run([one,group('reuse',[src(2)],[target('a')],'1:1','CONTENT_CONTRIBUTION')]).status,'PASS','contribution is not exclusive identity');
assert.ok(has(run([group('wrong-type',[src('1')],[target('a')],'1:1')]),'UNRESOLVED_SOURCE'));
assert.ok(has(run([group('missing',[src(1)],[target('missing')],'1:1')]),'UNRESOLVED_TARGET'));
assert.ok(has(run([one],[target('a'),target('a')]),'DUPLICATE_TARGET_IDENTITY'));
const revised=structuredClone(one);revised.sourceSnapshot.sha256='0'.repeat(64);
assert.ok(has(run([revised]),'SOURCE_SNAPSHOT_MISMATCH'));
const unversioned=structuredClone(one);delete unversioned.targets[0].version;
assert.ok(has(run([unversioned]),'UNRESOLVED_TARGET'));
const forged=structuredClone(one);forged.reviewStatus='VERIFIED';
assert.ok(has(run([forged]),'UNSUPPORTED_REVIEW_STATUS'));
const noEvidence=structuredClone(one);noEvidence.evidence=[];
assert.ok(has(run([noEvidence]),'MISSING_EVIDENCE'));
assert.ok(has(preflightLegacyMappingCandidates(createLegacyCatalogView(actual),[one],declarations),'SOURCE_PROVENANCE_INCOMPLETE'));
assert.equal(preflightLegacyMappingCandidates(view,{},[]).status,'FAIL');
assert.equal(preflightLegacyMappingCandidates(null).status,'FAIL');
assert.ok(has(preflightLegacyMappingCandidates({kind:'LEGACY_CATALOG_VIEW',source,audit:{}}),'SOURCE_CATALOG_INVALID'));
assert.ok(has(preflightLegacyMappingCandidates({kind:'LEGACY_CATALOG_VIEW',source,audit:{checks:[null]}}),'SOURCE_CATALOG_INVALID'));
assert.deepEqual(run([one]),run([one]),'diagnostics must be deterministic');
assert.equal(run([one]).verifiedMappingCount,0);
assert.equal(run([one]).migrationReadiness.status,'BLOCKED');
assert.equal(view.audit.testCases[9].status,'BLOCKED');
assert.ok(view.audit.testCases.filter(t=>t.status==='PASS').every(t=>['T01','T02','T03'].includes(t.id)));
assert.deepEqual(actual,before);
assert.deepEqual(source,view.source);
console.log('Legacy catalog view OK: lossless 90/88/6/13/10, typed lookup, 1:1/1:N/N:1, conflict rejection, frozen copies and candidate provenance. Verified mappings 0; production migration BLOCKED.');
